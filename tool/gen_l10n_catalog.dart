// ignore_for_file: avoid_print
import 'dart:io';

/// Génère `test/l10n/all_messages_catalog.g.dart` : un appel par message de
/// `AppLocalizations`, pour que `test/l10n/all_messages_test.dart` rende
/// chaque traduction française et anglaise et vérifie ses paramètres.
///
/// Source : les déclarations de `lib/l10n/generated/app_localizations.dart`
/// (`flutter gen-l10n`), qui donnent l'ordre et le type des paramètres.
///
/// À relancer après l'ajout de messages :
///   dart run tool/gen_l10n_catalog.dart && dart format test/l10n/
///
/// Un message absent du catalogue n'est simplement pas vérifié par ce test ;
/// un message retiré de l'ARB casse la compilation du catalogue, ce qui
/// rappelle de le régénérer.
void main() {
  const source = 'lib/l10n/generated/app_localizations.dart';
  const output = 'test/l10n/all_messages_catalog.g.dart';

  final code = File(source).readAsStringSync();
  final declaration = RegExp(
    r'^  String (?:get (\w+)|(\w+)\(([^)]*)\));',
    multiLine: true,
  );

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/gen_l10n_catalog.dart — ne pas modifier.')
    ..writeln('// Relancer : dart run tool/gen_l10n_catalog.dart')
    ..writeln()
    ..writeln("import 'package:dony/l10n/l10n.dart';")
    ..writeln()
    ..writeln('/// Marqueur passé à un paramètre texte [name] d\'un message')
    ..writeln('/// (type `String`, ou non typé dans l\'ARB).')
    ..writeln("String placeholderMarker(String name) => '<<\$name>>';")
    ..writeln()
    ..writeln('/// Valeur passée à tout paramètre numérique d\'un message.')
    ..writeln('const intPlaceholderValue = 3;')
    ..writeln()
    ..writeln('/// Chaque message de [AppLocalizations], rendu avec des')
    ..writeln('/// paramètres reconnaissables.')
    ..writeln(
      'final allMessages = <String, String Function(AppLocalizations)>{',
    );

  var count = 0;
  final textParameters = <String, List<String>>{};
  for (final m in declaration.allMatches(code)) {
    final getter = m.group(1);
    if (getter != null) {
      buffer.writeln("  '$getter': (l) => l.$getter,");
    } else {
      final name = m.group(2)!;
      final args = m
          .group(3)!
          .split(',')
          .map((p) => p.trim())
          .where((p) => p.isNotEmpty)
          .map((p) {
            final parts = p.split(RegExp(r'\s+'));
            final type = parts.first;
            final param = parts.last;
            return switch (type) {
              'String' || 'Object' => () {
                (textParameters[name] ??= []).add(param);
                return "placeholderMarker('$param')";
              }(),
              'int' || 'num' => 'intPlaceholderValue',
              _ => throw StateError('Type $type non géré ($name.$param)'),
            };
          })
          .join(', ');
      buffer.writeln("  '$name': (l) => l.$name($args),");
    }
    count++;
  }
  buffer
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// Paramètres texte (`String` ou non typés) de chaque message qui',
    )
    ..writeln('/// en a, dans l\'ordre de la signature.')
    ..writeln('const textParameters = <String, List<String>>{');
  textParameters.forEach((name, params) {
    final list = params.map((p) => "'$p'").join(', ');
    buffer.writeln("  '$name': [$list],");
  });
  buffer.writeln('};');

  File(output).writeAsStringSync(buffer.toString());
  print('$count messages écrits dans $output');
}
